def display_cat(row):
    t = str(row.get("类型") or "")
    body = str(row.get("正文") or "")
    name = str(row.get("名称") or "")
    if row.get("展示分类"):
        return row["展示分类"]
    if t == "战斗":
        return "战斗事件"
    if t in ("事件", "商店"):
        return "选项事件"
    if t in ("问心", "灵藏"):
        return "翻牌事件"
    if t == "剧情":
        talk = ("青棠" in body or "青棠" in name) and any(k in body for k in ("道", "问", "说", "应"))
        if talk or ("苏锦书" in body and any(k in body for k in ("道", "说", "塞", "写"))):
            return "对话事件"
        return "剧情事件"
    return "剧情事件"


def headers_of(ws):
    headers = {}
    for col in range(1, ws.max_column + 1):
        v = ws.cell(1, col).value
        if v is not None and str(v).strip():
            headers[str(v).strip()] = col
    return headers


def ensure_col(ws, headers, name):
    if name in headers:
        return headers[name]
    col = (max(headers.values()) if headers else 0) + 1
    ws.cell(1, col, name)
    headers[name] = col
    return col


def last_data_row(ws):
    last = 1
    for r in range(2, ws.max_row + 1):
        if any(ws.cell(r, c).value not in (None, "") for c in range(1, ws.max_column + 1)):
            last = r
    return last


def find_row(ws, headers, cond):
    for r in range(2, last_data_row(ws) + 1):
        ok = True
        for k, v in cond.items():
            if k not in headers:
                ok = False
                break
            if str(ws.cell(r, headers[k]).value or "") != str(v):
                ok = False
                break
        if ok:
            return r
    return None


def upsert(ws, headers, id_map, values, extra=None):
    row = dict(values)
    if extra:
        row.update(extra)
    for k in list(row.keys()):
        ensure_col(ws, headers, k)
    r = find_row(ws, headers, id_map)
    if r is None:
        r = last_data_row(ws) + 1
        for k, v in id_map.items():
            ws.cell(r, headers[k], v)
    for k, v in row.items():
        if k in id_map:
            continue
        ws.cell(r, headers[k], v)
    return r


def sheet_to_dicts(ws):
    rows = list(ws.iter_rows(values_only=True))
    if not rows:
        return []
    headers = []
    for h in rows[0]:
        headers.append("" if h is None else str(h).strip())
    while headers and headers[-1] == "":
        headers.pop()
    out = []
    for row in rows[1:]:
        if row is None or all(c is None or str(c).strip() == "" for c in row[: len(headers)]):
            continue
        first = row[0]
        if first is not None and str(first).strip() in headers:
            continue
        item = {}
        empty = True
        for i, key in enumerate(headers):
            if not key:
                continue
            val = row[i] if i < len(row) else None
            if val is None:
                item[key] = ""
            elif isinstance(val, float) and val.is_integer():
                item[key] = int(val)
                empty = False
            else:
                item[key] = val
                if str(val).strip() != "":
                    empty = False
        if not empty:
            out.append(item)
    return out


